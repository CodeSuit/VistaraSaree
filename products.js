// Currency exchange rates relative to INR
const CURRENCIES = {
  INR: { symbol: "₹", rate: 1, name: "Indian Rupee" },
  USD: { symbol: "$", rate: 0.012, name: "US Dollar" },
  EUR: { symbol: "€", rate: 0.011, name: "Euro" },
  GBP: { symbol: "£", rate: 0.0095, name: "British Pound" },
  AED: { symbol: "AED ", rate: 0.044, name: "UAE Dirham" }
};

// Global format currency utility
function formatPrice(priceINR, currency = "INR") {
  const curr = CURRENCIES[currency] || CURRENCIES.INR;
  const converted = Math.round(priceINR * curr.rate);
  if (currency === "INR") {
    return `${curr.symbol}${converted.toLocaleString("en-IN")}`;
  }
  return `${curr.symbol}${converted.toLocaleString("en-US")}`;
}
